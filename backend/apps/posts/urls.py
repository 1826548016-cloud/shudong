from django.urls import include, path
from rest_framework.routers import DefaultRouter

from .views import (
    AdminCommentMarkReadAPIView,
    AdminCommentReplyAPIView,
    AdminLoginView,
    AdminUnreadCommentCountAPIView,
    AdminUnreadCommentListAPIView,
    AIChatView,
    BlockedKeywordDestroyView,
    BlockedKeywordListCreateView,
    CommentDestroyAPIView,
    CommentListCreateAPIView,
    ContentReviewApproveAPIView,
    ContentReviewCountAPIView,
    ContentReviewListAPIView,
    ContentReviewRejectAPIView,
    MessageDestroyAPIView,
    MessageListCreateAPIView,
    MusicDestroyAPIView,
    MusicListAPIView,
    PostMediaDestroyView,
    PostViewSet,
    SiteAnnouncementDestroyView,
    SiteAnnouncementListCreateView,
    SiteAnnouncementPublicView,
    SiteAnnouncementUpdateView,
    SiteProfileAdminAPIView,
    SiteProfilePublicAPIView,
    TimelineMediaDestroyView,
    TimelineMediaDetailView,
    TimelineMediaListCreateView,
)

